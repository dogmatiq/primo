package option

import (
	"fmt"
	"go/token"
	"path"
	"strings"
	"unicode"
	"unicode/utf8"

	"google.golang.org/protobuf/types/descriptorpb"
)

// GoPackage returns the qualified name of the Go package, based on the .proto
// file's 'go_package' option.
func GoPackage(d *descriptorpb.FileDescriptorProto) (string, string, error) {
	pkg := d.GetOptions().GetGoPackage()
	if pkg == "" {
		return "", "", fmt.Errorf(
			"%s does not specify a 'go_package' option",
			d.GetName(),
		)
	}

	if importPath, name, ok := strings.Cut(pkg, ";"); ok {
		// If a semi-colon is present, the part after the semi-colon is the
		// actual package name. Used when the import path and package name
		// differ.
		//
		// Use of this option is discouraged. See
		// https://developers.google.com/protocol-buffers/docs/reference/go-generated
		if err := validatePackageName(name); err != nil {
			return "", "", fmt.Errorf(
				"%s specifies an invalid Go package name in its 'go_package' option (%q): %w",
				d.GetName(),
				pkg,
				err,
			)
		}

		return importPath, name, nil
	}

	return pkg, sanitizePackageName(path.Base(pkg)), nil
}

// validatePackageName returns an error if name is not a valid Go package name.
func validatePackageName(name string) error {
	if token.IsKeyword(name) {
		return fmt.Errorf("%q is a Go keyword", name)
	}

	if !token.IsIdentifier(name) {
		return fmt.Errorf("%q is not a valid Go identifier", name)
	}

	return nil
}

// sanitizePackageName converts name to a valid Go package name.
//
// It uses the same algorithm as protoc-gen-go so that the generated code is
// placed in the same package as the code generated by protoc-gen-go.
func sanitizePackageName(name string) string {
	name = strings.Map(
		func(r rune) rune {
			if unicode.IsLetter(r) || unicode.IsDigit(r) {
				return r
			}
			return '_'
		},
		name,
	)

	r, _ := utf8.DecodeRuneInString(name)
	if token.IsKeyword(name) || !unicode.IsLetter(r) {
		return "_" + name
	}

	return name
}
